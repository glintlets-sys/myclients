#!/usr/bin/env bash
# Serve the publish-time SEO pages (CDN bucket, seo/<tenant>/…) from the storefront's CloudFront distribution.
# Idempotent. DRY RUN by default: prints the planned changes and the distribution-config diff; --apply makes them.
#
#   tools/storefront-seo-cloudfront.sh [--apply] [--profile P] [--tenant T] [--stage S] [--distribution ID]
#                                      [--catalog-path /stone-solutions] [--no-home]
#   defaults: --profile all-access-admin --tenant wilber-stage --stage prod --distribution EBUFHWO6SEHTO
#
# What it sets up (nothing else in the distribution changes; the S3 website origin + SPA fallback stay as they are):
#   * origin "glint-seo-cdn"      → <CdnBucketName>.s3.ap-south-1.amazonaws.com via an Origin Access Control
#                                   (OAC "glint-seo-<distribution>", created if missing). The bucket policy that lets
#                                   this distribution read seo/* lives in the backend's CommerceStack
#                                   (InfraApp.STOREFRONT_DISTRIBUTIONS) — deploy GlintCommerce-<stage> first.
#   * CloudFront Function "storefront-seo-<distribution>" (cloudfront-js-2.0, viewer-request):
#        /product/<x>, /category/<x>, /blog/<x>, /blogs, <catalog-path>  → /seo/<tenant>/<path>/index.html
#        /sitemap.xml, /robots.txt                                      → /seo/<tenant>/…
#        /  (exactly)                                                   → /seo/<tenant>/index.html on glint-seo-cdn
#                                                                         (cf.selectRequestOriginById; --no-home skips)
#        /stone-solution/<x>                                            → 301 /category/<x>
#        anything else                                                  → unchanged (S3 website origin, SPA)
#   * cache behaviors for those path patterns → glint-seo-cdn (CachingOptimized: honours the pages' 300 s max-age)
#   * the function on the default behavior (only for "/"; every other path passes through untouched)
#   * custom error response 403 → /index.html (200): a page the publisher has not written (OAC returns 403 for a missing
#     key) falls back to the SPA, exactly like a deep link does today.
set -euo pipefail
export MSYS_NO_PATHCONV=1
APPLY=0; PROFILE=all-access-admin; TENANT=wilber-stage; STAGE=prod; DIST=EBUFHWO6SEHTO; CATALOG=/stone-solutions; HOME_PAGE=1
while [[ $# -gt 0 ]]; do
  case "$1" in
    --apply) APPLY=1 ;;
    --profile) PROFILE="$2"; shift ;;
    --tenant) TENANT="$2"; shift ;;
    --stage) STAGE="$2"; shift ;;
    --distribution) DIST="$2"; shift ;;
    --catalog-path) CATALOG="$2"; shift ;;
    --no-home) HOME_PAGE=0 ;;
    *) echo "unknown argument $1" >&2; exit 2 ;;
  esac
  shift
done
[[ "$TENANT" =~ ^[a-z0-9-]+$ ]] || { echo "bad tenant id" >&2; exit 2; }
[[ "$CATALOG" =~ ^/[A-Za-z0-9._~-]+$ ]] || { echo "bad catalog path" >&2; exit 2; }
REGION=ap-south-1
AWS=(aws --profile "$PROFILE" --region "$REGION")
ORIGIN_ID=glint-seo-cdn
FN_NAME="storefront-seo-${DIST}"
OAC_NAME="glint-seo-${DIST}"
WORK="$(mktemp -d)"
if command -v cygpath >/dev/null 2>&1; then WORK="$(cygpath -m "$WORK")"; fi   # node/aws on Windows need C:/ paths
trap 'rm -rf "$WORK"' EXIT

ACCOUNT="$("${AWS[@]}" sts get-caller-identity --query Account --output text)"
CDN_BUCKET="$("${AWS[@]}" cloudformation describe-stacks --stack-name "GlintCommerce-${STAGE}" \
  --query "Stacks[0].Outputs[?OutputKey=='CdnBucketName'].OutputValue" --output text)"
[[ -n "$CDN_BUCKET" && "$CDN_BUCKET" != "None" ]] || { echo "no CdnBucketName output on GlintCommerce-${STAGE}" >&2; exit 1; }
ORIGIN_DOMAIN="${CDN_BUCKET}.s3.${REGION}.amazonaws.com"
FN_ARN="arn:aws:cloudfront::${ACCOUNT}:function/${FN_NAME}"

echo "Distribution : $DIST"
echo "Tenant       : $TENANT  (pages: s3://$CDN_BUCKET/seo/$TENANT/)"
echo "Mode         : $([[ $APPLY == 1 ]] && echo APPLY || echo 'dry run (pass --apply to change anything)')"
echo

# ---------- CloudFront Function ----------
cat > "$WORK/function.js" <<JS
import cf from 'cloudfront';

// Generated by tools/storefront-seo-cloudfront.sh — maps SEO paths to the pages the catalog publish writes.
var TENANT = '${TENANT}';
var CATALOG = '${CATALOG}';
var SEO_ORIGIN = '${ORIGIN_ID}';
var HOME = ${HOME_PAGE};
var PAGE = /^\/(product|category|blog)\/[^\/]+$/;

function query(qs) {
  var parts = [];
  for (var k in qs) {
    var v = qs[k];
    if (v.multiValue) v.multiValue.forEach(function (m) { parts.push(k + '=' + m.value); });
    else parts.push(v.value === '' ? k : k + '=' + v.value);
  }
  return parts.length ? '?' + parts.join('&') : '';
}

function handler(event) {
  var r = event.request;
  var uri = r.uri;
  if (uri.length > 1 && uri.charAt(uri.length - 1) === '/') uri = uri.replace(/\/+$/, '');
  var old = uri.match(/^\/stone-solution\/([^\/]+)$/);
  if (old) {
    return { statusCode: 301, statusDescription: 'Moved Permanently',
      headers: { location: { value: '/category/' + old[1] + query(r.querystring) }, 'cache-control': { value: 'public, max-age=86400' } } };
  }
  if (uri === '/' && r.uri === '/') {
    if (!HOME) return r;
    cf.selectRequestOriginById(SEO_ORIGIN);
    r.uri = '/seo/' + TENANT + '/index.html';
    return r;
  }
  if (uri === '/sitemap.xml' || uri === '/robots.txt') {
    r.uri = '/seo/' + TENANT + uri;
    return r;
  }
  if (uri === CATALOG || uri === '/blogs' || PAGE.test(uri)) {
    r.uri = '/seo/' + TENANT + uri + '/index.html';
  }
  return r;
}
JS

FN_ETAG=""
if "${AWS[@]}" cloudfront describe-function --name "$FN_NAME" --stage DEVELOPMENT > "$WORK/fn.json" 2>/dev/null; then
  FN_ETAG="$(node -e 'console.log(require(process.argv[1]).ETag)' "$WORK/fn.json")"
  "${AWS[@]}" cloudfront get-function --name "$FN_NAME" --stage LIVE "$WORK/live.js" >/dev/null 2>&1 || : > "$WORK/live.js"
  if cmp -s "$WORK/function.js" "$WORK/live.js"; then
    echo "[function] $FN_NAME: LIVE code is up to date"
    FN_ACTION=none
  else
    echo "[function] $FN_NAME: update + publish. Code diff (LIVE → planned):"
    diff -u "$WORK/live.js" "$WORK/function.js" | sed 's/^/    /' || true
    FN_ACTION=update
  fi
else
  echo "[function] $FN_NAME: create + publish (cloudfront-js-2.0). Code:"
  sed 's/^/    /' "$WORK/function.js"
  FN_ACTION=create
fi
echo

# ---------- Origin Access Control ----------
OAC_ID="$("${AWS[@]}" cloudfront list-origin-access-controls \
  --query "OriginAccessControlList.Items[?Name=='${OAC_NAME}'].Id | [0]" --output text 2>/dev/null || true)"
if [[ -z "$OAC_ID" || "$OAC_ID" == "None" ]]; then
  echo "[oac] $OAC_NAME: create (s3, sigv4, always sign)"
  OAC_ID="<new-oac-id>"
  OAC_ACTION=create
else
  echo "[oac] $OAC_NAME: exists ($OAC_ID)"
  OAC_ACTION=none
fi
echo

# ---------- Distribution config ----------
"${AWS[@]}" cloudfront get-distribution-config --id "$DIST" > "$WORK/dist.json"
ETAG="$(node -e 'console.log(require(process.argv[1]).ETag)' "$WORK/dist.json")"

plan_config() { # $1 = OAC id to write into the config
  node - "$WORK/dist.json" "$WORK/current.json" "$WORK/planned.json" "$ORIGIN_ID" "$ORIGIN_DOMAIN" "$1" "$FN_ARN" "$CATALOG" "$HOME_PAGE" <<'NODE'
const fs = require('fs');
const [file, curOut, planOut, originId, domain, oacId, fnArn, catalog, home] = process.argv.slice(2);
const cfg = JSON.parse(fs.readFileSync(file, 'utf8')).DistributionConfig;
fs.writeFileSync(curOut, JSON.stringify(cfg, null, 2) + '\n');
const c = JSON.parse(JSON.stringify(cfg));

// Origin
const origin = {
  Id: originId, DomainName: domain, OriginPath: '', CustomHeaders: { Quantity: 0 },
  S3OriginConfig: { OriginAccessIdentity: '' }, ConnectionAttempts: 3, ConnectionTimeout: 10,
  OriginShield: { Enabled: false }, OriginAccessControlId: oacId
};
const others = c.Origins.Items.filter(o => o.Id !== originId);
c.Origins.Items = [...others, origin];
c.Origins.Quantity = c.Origins.Items.length;

// Cache behaviors (ours replaced in place; anyone else's kept, ahead of ours)
const fnAssoc = { Quantity: 1, Items: [{ FunctionARN: fnArn, EventType: 'viewer-request' }] };
const patterns = ['/product/*', '/category/*', '/blog/*', '/blogs', catalog, '/sitemap.xml', '/robots.txt', '/stone-solution/*'];
const behavior = p => ({
  PathPattern: p, TargetOriginId: originId,
  TrustedSigners: { Enabled: false, Quantity: 0 }, TrustedKeyGroups: { Enabled: false, Quantity: 0 },
  ViewerProtocolPolicy: 'redirect-to-https',
  AllowedMethods: { Quantity: 2, Items: ['HEAD', 'GET'], CachedMethods: { Quantity: 2, Items: ['HEAD', 'GET'] } },
  SmoothStreaming: false, Compress: true,
  LambdaFunctionAssociations: { Quantity: 0 }, FunctionAssociations: fnAssoc,
  FieldLevelEncryptionId: '', CachePolicyId: '658327ea-f89d-4fab-a63d-7e88639e58f6' // Managed-CachingOptimized
});
const existing = (c.CacheBehaviors.Items || []);
const foreign = existing.filter(b => !patterns.includes(b.PathPattern) && b.TargetOriginId !== originId);
const clash = existing.filter(b => patterns.includes(b.PathPattern) && b.TargetOriginId !== originId);
if (clash.length) { console.error('Refusing: these path patterns already route elsewhere: ' + clash.map(b => b.PathPattern).join(', ')); process.exit(3); }
c.CacheBehaviors.Items = [...foreign, ...patterns.map(behavior)];
c.CacheBehaviors.Quantity = c.CacheBehaviors.Items.length;

// Default behavior: the function (for "/"), keeping any other event types it already has.
const d = c.DefaultCacheBehavior;
const assoc = (d.FunctionAssociations && d.FunctionAssociations.Items) || [];
const otherViewerReq = assoc.find(a => a.EventType === 'viewer-request' && a.FunctionARN !== fnArn);
if (home === '1') {
  if (otherViewerReq) { console.error('Refusing: default behavior already has viewer-request function ' + otherViewerReq.FunctionARN); process.exit(3); }
  const items = [...assoc.filter(a => a.EventType !== 'viewer-request'), { FunctionARN: fnArn, EventType: 'viewer-request' }];
  d.FunctionAssociations = { Quantity: items.length, Items: items };
} else {
  const items = assoc.filter(a => a.FunctionARN !== fnArn);
  d.FunctionAssociations = items.length ? { Quantity: items.length, Items: items } : { Quantity: 0 };
}

// 403 (missing key through OAC) → SPA, like the existing 404 rule.
const errs = (c.CustomErrorResponses.Items || []).filter(e => e.ErrorCode !== 403);
errs.push({ ErrorCode: 403, ResponsePagePath: '/index.html', ResponseCode: '200', ErrorCachingMinTTL: 10 });
errs.sort((a, b) => a.ErrorCode - b.ErrorCode);
c.CustomErrorResponses = { Quantity: errs.length, Items: errs };

fs.writeFileSync(planOut, JSON.stringify(c, null, 2) + '\n');
NODE
}

plan_config "$OAC_ID"
if cmp -s "$WORK/current.json" "$WORK/planned.json"; then
  echo "[distribution] $DIST: config is up to date"
  DIST_ACTION=none
else
  echo "[distribution] $DIST: update. Config diff (current → planned):"
  diff -u "$WORK/current.json" "$WORK/planned.json" | sed 's/^/    /' || true
  DIST_ACTION=update
fi
echo

if [[ $APPLY != 1 ]]; then
  echo "Dry run only. Before --apply: deploy GlintCommerce-${STAGE} (bucket policy for seo/*), deploy the storefront with"
  echo "tools/deploy-store.sh (uploads seo/${TENANT}/_shell.html and republishes), and check s3://$CDN_BUCKET/seo/${TENANT}/index.html exists."
  exit 0
fi

# ---------- apply ----------
if [[ $FN_ACTION == create ]]; then
  "${AWS[@]}" cloudfront create-function --name "$FN_NAME" \
    --function-config "Comment=SEO pages for ${TENANT} (storefront-seo-cloudfront.sh),Runtime=cloudfront-js-2.0" \
    --function-code "fileb://$WORK/function.js" > "$WORK/fn.json"
  FN_ETAG="$(node -e 'console.log(require(process.argv[1]).ETag)' "$WORK/fn.json")"
elif [[ $FN_ACTION == update ]]; then
  "${AWS[@]}" cloudfront update-function --name "$FN_NAME" --if-match "$FN_ETAG" \
    --function-config "Comment=SEO pages for ${TENANT} (storefront-seo-cloudfront.sh),Runtime=cloudfront-js-2.0" \
    --function-code "fileb://$WORK/function.js" > "$WORK/fn.json"
  FN_ETAG="$(node -e 'console.log(require(process.argv[1]).ETag)' "$WORK/fn.json")"
fi
if [[ $FN_ACTION != none ]]; then
  "${AWS[@]}" cloudfront publish-function --name "$FN_NAME" --if-match "$FN_ETAG" >/dev/null
  echo "function $FN_NAME published"
fi

if [[ $OAC_ACTION == create ]]; then
  OAC_ID="$("${AWS[@]}" cloudfront create-origin-access-control --origin-access-control-config \
    "Name=${OAC_NAME},Description=Storefront ${DIST} reads seo/* from the Glint CDN bucket,SigningProtocol=sigv4,SigningBehavior=always,OriginAccessControlOriginType=s3" \
    --query OriginAccessControl.Id --output text)"
  echo "OAC $OAC_NAME created: $OAC_ID"
  plan_config "$OAC_ID"
fi

if [[ $DIST_ACTION == update || $OAC_ACTION == create ]]; then
  "${AWS[@]}" cloudfront update-distribution --id "$DIST" --if-match "$ETAG" \
    --distribution-config "file://$WORK/planned.json" --query Distribution.Status --output text
  echo "distribution $DIST updating (takes a few minutes). Check: curl -sI https://<storefront>/robots.txt"
fi
echo "Done."
